import json

d = json.load(open("path_a_numbers.json"))

def mat(name, m):
    rows = "".join("<tr>" + "".join("<td>%.3f</td>" % v for v in r) + "</tr>" for r in m)
    return "<h3>" + name + "</h3><table><tbody>" + rows + "</tbody></table>"

CSS = ("body{font:14px/1.55 Georgia,serif;max-width:780px;margin:24px auto;color:#111}"
       "table{border-collapse:collapse;width:100%;margin:8px 0 20px}"
       "td{border:1px solid #999;padding:6px 8px;text-align:right;font-family:ui-monospace,monospace}"
       "th{border:1px solid #999;padding:6px 8px;text-align:left;background:#eee}"
       "h1,h2,h3{font-family:system-ui}"
       ".note{color:#555;font-size:12px}")

parts = []
parts.append("<h1>Path A: Attention Computed by Hand</h1>")
parts.append("<p class=note>Every number below is generated by path_a_walkthrough.py "
             "(B=1, N=3 tokens, D=8, d_k=4, d_v=4). Shapes are annotated.</p>")
parts.append(mat("X: input embeddings (3 x 8)", d["X"]))
parts.append(mat("PE: sinusoidal positional encoding (3 x 8, shown as pairs)", d["PE"]))
parts.append(mat("X + PE (3 x 8)", d["Xin"]))
parts.append(mat("Q = X W_Q (3 x 4)", d["Q"]))
parts.append(mat("K = X W_K (3 x 4)", d["K"]))
parts.append(mat("V = X W_V (3 x 4)", d["V"]))
parts.append(mat("S = Q K^T  raw scores (3 x 3)", d["S"]))
parts.append(mat("S / sqrt(d_k), sqrt(4)=2 (3 x 3)", d["Sn"]))
parts.append(mat("A = softmax row-wise (3 x 3)", d["A"]))
parts.append(mat("Z = A V  context vectors (3 x 4)", d["Z"]))
parts.append(mat("A_masked: causal mask applied (3 x 3)", d["Am"]))
parts.append(mat("Z_masked = A_masked V (3 x 4)", d["Zm"]))
parts.append("<p class=note>Each row of A and A_masked sums to 1.0. "
             "In A_masked, every future position above the diagonal is exactly 0.0, "
             "which is the -inf mask becoming zero probability after softmax.</p>")

html = ("<!doctype html><html><head><meta charset=utf-8>"
        "<title>Path A Walkthrough</title><style>" + CSS + "</style></head><body>"
        + "".join(parts) + "</body></html>")

open("path_a_walkthrough.html", "w").write(html)
print("wrote path_a_walkthrough.html", len(html), "chars, sections:", len(parts))
